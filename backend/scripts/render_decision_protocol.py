#!/usr/bin/env python
"""Write `docs/decision-protocol.md` from `app/decision_protocol.py`, and check it has not drifted.

The decision model is a typed call rather than an agent (ADR-0021), so its protocol is the thing a reader
should be able to inspect: which questions are asked, of which role, with which answer vocabulary, under
which gates. This renders that from the module — the module is the source of truth, the document is the
rendering — and `--check` refuses a document that no longer matches the module or the pinned digest.

    cd backend && .venv/bin/python scripts/render_decision_protocol.py            # write
    cd backend && .venv/bin/python scripts/render_decision_protocol.py --check    # verify
    cd backend && .venv/bin/python scripts/render_decision_protocol.py --print-digest

Deliberately NOT in `scripts/check.sh`: the module's digest is asserted by
`backend/tests/test_decision_protocol.py`, which the gate already runs, so a second check here would be
the same assertion twice.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "backend"))

# pi-lens-ignore: reportMissingImports
from app import decision_model, decision_protocol  # noqa: E402

TARGET = ROOT / "docs" / "decision-protocol.md"

# The short UI reading for each urgency level. It lives in the renderer rather than in the frontend so the
# document is the frontend's source of truth: `frontend/src/challenge-demo.mjs` holds the labels and its test
# fails if the two disagree. A label is an *ordering basis*, never a patient-level verdict, and each one names
# its own limit rather than stating a clinical severity ([ADR-0024](adr/0024-the-urgency-legend-is-an-ordering-basis.md)).
URGENCY_UI_LABELS = (
    "ei vaikuta ajoitukseen",
    "tavanomainen käynti",
    "selvitä tällä käynnillä",
    "nopea huomio",
    "aikakriittinen",
)


def render() -> str:
    signature = decision_protocol.signature()
    lines: list[str] = []
    lines.append("<!-- Generated by backend/scripts/render_decision_protocol.py. Do not edit by hand: -->")
    lines.append("<!-- regenerate it, and update SIGNATURE_SHA256 in app/decision_protocol.py. -->")
    lines.append("")
    lines.append("# The Decision-1 protocol, as a pinned value")
    lines.append("")
    lines.append("Microsoft-Decision-1 is reached as a **typed call**, not as an agent: a `state` plus")
    lines.append("`questions`, each question a `choice`, `score` or `noul`, answered with probabilities. That is")
    lines.append("the surface this repository audits, and [ADR-0021](adr/0021-decision-1-stays-a-typed-call.md)")
    lines.append("records why it stays that way. One model answers both roles")
    lines.append("([ADR-0018](adr/0018-microsoft-decision-1-replaces-the-vendor-classifier.md)).")
    lines.append("")
    lines.append(f"- Model: `{signature['model']}`")
    lines.append(f"- Route: `{signature['route']}`")
    lines.append(f"- Signature SHA-256: `{decision_protocol.SIGNATURE_SHA256}`")
    lines.append("- Deployment name is configuration (`LUVN_DECISION_DEPLOYMENT`), default `Decision-1`.")
    lines.append("")
    for role in decision_protocol.ROLES:
        lines.append(f"## Role: `{role}`")
        lines.append("")
        lines.append("`state` fields sent: " + ", ".join(f"`{f}`" for f in signature["state_fields"][role]))
        lines.append("")
        lines.append("| Question | Wire type | Answer vocabulary | What it is for |")
        lines.append("| --- | --- | --- | --- |")
        for question in signature["questions"][role]:
            answers = question["answers"]
            if isinstance(answers, tuple):
                answers = ", ".join(f"`{a}`" for a in answers)
            elif answers is None:
                answers = "boolean-shaped (`noul`)"
            lines.append(f"| `{question['name']}` | `{question['type']}` | {answers} | {question['used_for']} |")
        lines.append("")
    lines.append("## The urgency legend, in the classifier's own words")
    lines.append("")
    lines.append("These five strings are the `criteria` the `urgency` question sends, and they are the only")
    lines.append("urgency wording this system displays: it renders the classifier's own answer rather than")
    lines.append("composing a sentence of its own. **The limit travels with the legend** — the levels describe")
    lines.append("*scheduling* urgency, never treatment urgency, and a level is never shown as a patient-level")
    lines.append("verdict: it orders already-eligible records and nothing else. The UI shows the leading level's")
    lines.append("text beside its distribution, labelled as an ordering basis")
    lines.append("([ADR-0024](adr/0024-the-urgency-legend-is-an-ordering-basis.md)).")
    lines.append("")
    lines.append("| Level | The classifier's legend text | UI label |")
    lines.append("| --- | --- | --- |")
    for index, legend_text in enumerate(decision_model.URGENCY_LEVELS):
        lines.append(f"| {index} | {legend_text} | {URGENCY_UI_LABELS[index]} |")
    lines.append("")
    lines.append("The third column is what the interface shows beside the level's distribution. It is a **short")
    lines.append("reading label, not a claim**: `frontend/src/challenge-demo.test.mjs` fails if these three")
    lines.append("columns disagree with each other or with the module, so the label, the legend and the question")
    lines.append("cannot drift apart silently.")
    lines.append("")
    lines.append("## Gates applied to the answers")
    lines.append("")
    for gate in signature["gates"]:
        lines.append(f"- {gate}")
    lines.append("")
    lines.append("## What this protocol does not do")
    lines.append("")
    lines.append("It does not grant permission. Person/source binding and the role/purpose cut run before it,")
    lines.append("and a withheld record's identity, text and count are never sent to it or derived from its")
    lines.append("answers. It does not decide: a proposal is advisory, `unclear` is fail-closed, and the")
    lines.append("deterministic rule engine stays the authority. It is also not a clinical instrument.")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify the committed document matches the module")
    parser.add_argument("--print-digest", action="store_true", help="print the digest for SIGNATURE_SHA256")
    args = parser.parse_args()

    if args.print_digest:
        print(decision_protocol.digest())
        return 0

    current = decision_protocol.digest()
    if current != decision_protocol.SIGNATURE_SHA256:
        print(f"check: the descriptor does not match the pinned digest\n"
              f"  pinned:    {decision_protocol.SIGNATURE_SHA256}\n"
              f"  computed:  {current}\n"
              "Update SIGNATURE_SHA256 in backend/app/decision_protocol.py and regenerate this document "
              "if the protocol change is intended.", file=sys.stderr)
        return 1

    rendered = render()
    if args.check:
        if not TARGET.is_file():
            print(f"check: no document at {TARGET.relative_to(ROOT)}", file=sys.stderr)
            return 1
        if TARGET.read_text(encoding="utf-8") != rendered:
            print(f"check: {TARGET.relative_to(ROOT)} does not match the module; regenerate it",
                  file=sys.stderr)
            return 1
        print(f"check: decision-protocol.md matches the module (sha256 "
              f"{decision_protocol.SIGNATURE_SHA256[:12]}…)")
        return 0

    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(rendered, encoding="utf-8")
    print(f"  -> {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
