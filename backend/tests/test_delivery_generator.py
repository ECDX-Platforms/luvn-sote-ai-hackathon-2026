"""The generator must be able to regenerate a demo corpus: same vocabulary, same reconciliation.

The defect this pins (G1, 2026-10-11): `scripts/generate_delivery_corpus.py` emitted a vocabulary the
registry and `app.assess.score` do not accept — `assessments` as `phq9_total`/`iadl_total` totals instead
of a `vastaukset` item map, a `mittaus` payload of `tunnus`/`arvo`/`yksikkö` instead of the four render
keys, an unregistered `atc` on every medication, `kuvaus` where `asiointitapahtuma` wants
`kanava`/`suunta`/`aihe`/`yhteenveto`, and no `versio` on an assessment. It also crashed on import with
`NameError: name 'LAST_NAMES' is not defined`. A corpus generated by the shipped generator therefore
reconciled `warning` (or not at all), so the claim that the demo's next home "already exists and
is exercised" was true only of the hand-authored `delivery-demo`.

The proof is the reconciliation an operator is told to trust: `status: ready`, zero refused,
zero missing render keys. Named for the defect because a generator that passes every other test while
emitting an unregistered key is the failure that survived here.
"""

from __future__ import annotations

import json
from pathlib import Path

from app import assess, delivery, source
from scripts import generate_delivery_corpus

SEED = 20261013


def _generate(tmp_path: Path) -> Path:
    return generate_delivery_corpus.generate(
        tmp_path / "generated", profiles=24, records_min=5, records_max=12, encounters=6, seed=SEED)


def _rows(source_dir: Path) -> list[dict]:
    return [json.loads(line) for line in
            (source_dir / "records.jsonl").read_text(encoding="utf-8").splitlines() if line.strip()]


def test_generated_corpus_reconciles_ready_with_no_refusals_or_missing_render_keys(tmp_path: Path):
    source_dir = _generate(tmp_path)
    report = delivery.dry_run_delivery(source_dir, tmp_path / "dry")

    assert report.status == "ready", report.report_path.read_text(encoding="utf-8")
    assert report.rows_refused == 0
    assert report.rows_examined == report.records_seen

    document = json.loads(report.report_path.read_text(encoding="utf-8"))
    # Every canonical type is exercised, so a type-specific flag cannot hide by never being generated.
    assert set(document["types"]) == set(source.RECORD_TYPES)
    assert document["unmapped_record_types"] == {}
    assert document["unmapped_payload_keys_by_unmapped_type"] == {}
    for name, item in document["types"].items():
        assert item["rows_seen"] > 0, name
        assert item["missing_render_keys"] == {}, f"{name}: a render key no row carries"
        assert item["unmapped_payload_keys"] == {}, f"{name}: an unregistered payload key"
        assert item["useful_set_miss_rows"] == 0, f"{name}: a row with nothing useful"
        assert item["content_maps_to_nothing"] == 0, f"{name}: a row that renders nothing"
    # Every unit of the render vocabulary is supplied by at least one row of its type, apart from the optional vitals
    # (`delivery.OPTIONAL_RENDER_KEYS`), whose absence is not a gap: the generator writes no thermometer.
    for record_type, render_keys in delivery.RENDER_PAYLOAD_KEYS.items():
        carried = set()
        for row in _rows(source_dir):
            if row["record_type"] == record_type:
                carried |= set(row["payload"])
        required = render_keys - delivery.OPTIONAL_RENDER_KEYS.get(record_type, set())
        assert required <= carried, f"{record_type} never carries {sorted(required - carried)}"


def test_generated_payload_keys_are_exactly_the_registered_vocabulary(tmp_path: Path):
    """The narrower defect, pinned directly: nothing the generator emits is an unregistered key."""
    source_dir = _generate(tmp_path)
    rows = _rows(source_dir)
    assert rows, "the generator produced no rows"
    for row in rows:
        registered = set(delivery.PAYLOAD_KEY_ALIASES[row["record_type"]])
        extra = set(row["payload"]) - registered
        assert not extra, f"{row['record_id']}: {sorted(extra)} is not a key {row['record_type']} declares"
        assert "atc" not in row["payload"], (
            "`atc` is not a registered payload key; the code system belongs on the envelope")
    # The code systems are carried on the envelope, where ADR-0015 puts the intent.
    assert {row.get("code_system") for row in rows if row["record_type"] == source.DIAGNOSIS} == {"ICD-10"}
    assert {row.get("code_system") for row in rows if row["record_type"] == source.MEDICATION} == {"ATC"}


def test_generated_assessments_are_item_maps_the_scorer_accepts(tmp_path: Path):
    """`assess.score` sums `vastaukset`; a generated `phq9_total` was a number nothing could read."""
    source_dir = _generate(tmp_path)
    rows = _rows(source_dir)
    assessments = [row for row in rows if row["record_type"] == source.ARVIOINTI]
    assert assessments, "the generated corpus carries no assessment"

    scored = {row["payload"]["instrumentti"] for row in assessments}
    assert {"PHQ-9", "IADL"} <= scored, f"the generated corpus never scores a known instrument: {scored}"
    # RAI is supplied, not implemented (ADR-0008): answers are recorded, the total is never invented.
    assert "RAI" in scored

    for row in assessments:
        instrument = row["payload"]["instrumentti"]
        spec = assess.INSTRUMENTS.get(instrument)
        answers = row["payload"]["vastaukset"]
        if spec is None:
            assert answers, f"{row['record_id']}: a supplied instrument with no recorded answers"
            continue
        assert set(answers) == set(spec.items), (
            f"{row['record_id']}: {instrument} answers {sorted(answers)} are not its declared items")
        record = delivery.Record.model_validate({**row, "source": "delivery"})
        result = assess.score(record)
        assert result.valmis is True and result.total == sum(answers.values())
        assert result.max_total == spec.max_total
    phq9 = next(row for row in assessments if row["payload"]["instrumentti"] == "PHQ-9")
    assert "q9" in phq9["payload"]["vastaukset"], (
        "item 9 is the item whose score most changes what happens next; a generated PHQ-9 must carry it")


def test_generated_corpus_imports_every_record_with_nothing_skipped(tmp_path: Path):
    """A `ready` dry run that then loses rows at import would make the reconciliation a lie."""
    source_dir = _generate(tmp_path)
    report = delivery.import_delivery(source_dir, tmp_path / "index")
    assert report.skipped == 0
    assert report.records == len(_rows(source_dir))
    assert report.personas == 24


def test_generated_corpus_carries_the_beat_bearing_vocabulary(tmp_path: Path):
    """What "a generated corpus covers every beat" can mean for a random generator.

    The beat *vocabulary* the hand-authored `delivery-demo` uses is now emitted deterministically: an
    active medication with missed doses beside a note that says it was stopped (the conflict and the
    adherence beats), a catalogue form whose due date has passed, both scored instruments with item 9
    present, a supplied and unscored RAI, four-key measurements, and the ADR-0015 code systems. The two
    beats that are relationships *between* records rather than a record's own shape — the same-fact
    duplicate pair and the guardian/self split — stay hand-authored in `delivery-demo`; a random stream
    has no counterpart to author them against.
    """
    source_dir = _generate(tmp_path)
    rows = _rows(source_dir)
    assert any(row["record_type"] == source.MEDICATION
               and row["payload"]["tila"] == source.MEDICATION_ACTIVE
               and row["payload"]["puuttuneet_annokset_30d"] > 0 for row in rows), (
        "no active medication with missed doses (the adherence beat)")
    assert any(row["record_type"] == source.FREE_TEXT and "keskeytyi" in row["payload"]["otsikko"]
               for row in rows), "no note carrying the stopped-medication vocabulary (the conflict beat)"
    due = [row for row in rows if (row.get("form") or {}).get("due_at")]
    assert due, "no catalogue row with a declared due date (the `due` beat)"
    assert all(row["form"]["due_at"] < "2026-10-13" for row in due)
    instruments = {row["payload"]["instrumentti"] for row in rows
                   if row["record_type"] == source.ARVIOINTI}
    assert {"PHQ-9", "IADL", "RAI"} <= instruments
    assert {"ICD-10", "ATC", "FinLOINC"} <= {row.get("code_system") for row in rows}
